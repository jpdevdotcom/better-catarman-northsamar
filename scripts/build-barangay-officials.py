"""Generates app/data/barangayOfficials.ts from the DILG Barangay Officials Directory.

Source: https://dilg.gov.ph/barangay-officials-directory (Barangay Information System).
Download one JSON file per barangay into a folder, named by DILG barangay code, from
  https://bis.dilg.gov.ph/bops/default/master-filter?region=08&province=048&citymun=05&brgy=<code>
then run:  python3 -I scripts/build-barangay-officials.py <folder> <date retrieved, e.g. "11 November 2026">

Only names and positions are published. Personal email addresses in the directory are left
out, and a contact number is kept only when it is a well-formed phone number.
"""
import json, pathlib, re, sys, unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
folder, retrieved = pathlib.Path(sys.argv[1]), sys.argv[2]

# DILG barangay code -> slug used on this site
CODES = {
    '001': 'aguinaldo', '002': 'airport-village', '003': 'baybay', '005': 'bocsol', '007': 'cabayhan', '008': 'cag-abaca',
    '010': 'cal-igang', '011': 'cawayan', '012': 'cervantes', '013': 'cularima', '015': 'daganas', '016': 'galutan',
    '018': 'malvar', '020': 'guba', '021': 'gebalagnan', '022': 'gibulwangan', '025': 'dona-pulqueria', '026': 'hinatad',
    '027': 'imelda', '028': 'liberty', '029': 'libjo', '032': 'mabini', '033': 'macagtas', '034': 'mckinley',
    '037': 'new-rizal', '038': 'old-rizal', '041': 'paticua', '042': 'polangi', '043': 'quezon', '045': 'salvacion',
    '049': 'san-julian', '051': 'somoge', '053': 'tinowaran', '054': 'trangue', '056': 'washington', '059': 'uep-zone-i',
    '060': 'uep-zone-ii', '061': 'uep-zone-iii', '062': 'acacia', '063': 'talisay', '064': 'molave', '065': 'yakal',
    '066': 'ipil-ipil', '067': 'jose-abad-santos', '068': 'casoy', '069': 'lapu-lapu', '070': 'santol', '071': 'narra',
    '072': 'calachuchi', '073': 'sampaguita', '074': 'mabolo', '075': 'jose-p-rizal', '076': 'bangkerohan', '077': 'dalakit',
    '078': 'san-pascual',
}
ORDER = ['Punong Barangay', 'Sangguniang Barangay Member', 'SK Chairperson', 'Barangay Secretary', 'Barangay Treasurer']
PARTICLES = {'de', 'del', 'dela', 'la', 'los', 'las', 'y'}
SUFFIXES = {'JR': 'Jr.', 'SR': 'Sr.', 'II': 'II', 'III': 'III', 'IV': 'IV'}

def cap(word):
    return '-'.join(p[:1].upper() + p[1:].lower() for p in word.split('-'))

def title(text):
    words = [w for w in re.sub(r'\s+', ' ', text or '').strip().split(' ') if w]
    return ' '.join(w.lower() if i and w.lower() in PARTICLES else cap(w) for i, w in enumerate(words))

def name(o):
    middle = (o.get('MIDDLENAME') or '').strip()
    suffix = (o.get('SUFFIX') or '').strip().upper().rstrip('.')
    parts = [title(o['FIRSTNAME']), (middle[0].upper() + '.') if middle else '', title(o['LASTNAME']), SUFFIXES.get(suffix, '')]
    return ' '.join(p for p in parts if p)

def phone(raw):
    d = re.sub(r'\D', '', raw or '')
    if re.fullmatch(r'09\d{9}', d):
        return f'{d[:4]}-{d[4:7]}-{d[7:]}'
    if re.fullmatch(r'(055)?5[01]0\d{4}', d):  # Catarman landline, with or without the 055 area code
        d = d[-7:]
        return f'(055) {d[:3]}-{d[3:]}'
    return None

out, total = {}, 0
for code, slug in CODES.items():
    rows = json.loads((folder / f'{code}.json').read_text(encoding='utf-8'))
    rows.sort(key=lambda o: ORDER.index(o['POSITION']) if o['POSITION'] in ORDER else 99)
    officials = [{'name': name(o), 'position': o['POSITION']} for o in rows]
    # The directory repeats the barangay's contact number on each row; take the Punong Barangay's.
    contact = next((phone(o.get('BH_TELNO')) for o in rows if phone(o.get('BH_TELNO'))), None)
    out[slug] = {'officials': officials, 'contact': contact}
    total += len(officials)

assert len(out) == 55
ts = '''// Generated by scripts/build-barangay-officials.py — edit that script, not this file.
// Source: DILG Barangay Officials Directory, https://dilg.gov.ph/barangay-officials-directory

export interface BarangayOfficial {
  name: string
  position: string
}

export interface BarangayOfficials {
  officials: BarangayOfficial[]
  /** Barangay contact number as listed by DILG, when it is a well-formed number. */
  contact: string | null
}

/** Date the directory was read. */
export const officialsRetrieved = %s

export const officialsSource = 'https://dilg.gov.ph/barangay-officials-directory'

/** Keyed by barangay slug. */
export const barangayOfficials: Record<string, BarangayOfficials> = %s
''' % (json.dumps(retrieved), json.dumps(out, ensure_ascii=False, indent=1))
(ROOT / 'app/data/barangayOfficials.ts').write_text(ts, encoding='utf-8')
print('barangays', len(out), 'officials', total, 'with contact', sum(1 for v in out.values() if v['contact']))
