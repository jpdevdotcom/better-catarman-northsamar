"""Generates app/data/boundaries.ts from the official NAMRIA/PSA boundaries in data-sources/.

Run:  python3 -I scripts/build-boundaries.py
"""
import json, pathlib, re, sys, unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'scripts'))
from geo import interior_point, rounded  # noqa: E402

SRC = ROOT / 'data-sources'
bgy = json.loads((SRC / 'namria-psa-barangays-catarman.json').read_text())['features']
mun = next(f for f in json.loads((SRC / 'namria-psa-municipalities-northern-samar.json').read_text())['features']
           if f['properties']['adm3_psgc'] == 804805000)

# PSA names that differ from the names used on this site.
ALIAS = {'gebulwangan': 'gibulwangan', 'general-malvar': 'malvar', 'kasoy': 'casoy',
         'uep-i': 'uep-zone-i', 'uep-ii': 'uep-zone-ii', 'uep-iii': 'uep-zone-iii'}


def slug(s):
    s = unicodedata.normalize('NFD', s.lower())
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn')
    s = re.sub(r'[^a-z0-9]+', '-', s).strip('-')
    return ALIAS.get(s, s)


shapes = {}
for f in bgy:
    x, y = interior_point(f['geometry'])
    shapes[slug(f['properties']['adm4_en'])] = {
        'psgc': f['properties']['adm4_psgc'],
        'center': {'lat': round(y, 5), 'lng': round(x, 5)},
        'polygons': rounded(f['geometry']),
    }
assert len(shapes) == 55, len(shapes)

ts = '''// Generated by scripts/build-boundaries.py from data-sources/. Edit the script, not this file.
// Boundaries: NAMRIA and PSA (PSGC 3Q 2026), via OCHA COD-AB, CC BY-IGO.

type Ring = [number, number][]

export interface BarangayShape {
  psgc: number
  /** A point inside the official boundary. */
  center: { lat: number, lng: number }
  /** [lng, lat] rings: polygons, each an outer ring then any holes. */
  polygons: Ring[][]
}

/** Official boundary of the Municipality of Catarman. */
export const municipalBoundary: Ring[][] = %s

/** Official barangay boundaries, keyed by barangay slug. */
export const barangayShapes: Record<string, BarangayShape> = %s

export const boundarySource = {
  label: 'NAMRIA and PSA administrative boundaries (PSGC 3Q 2026), via OCHA COD-AB',
  url: 'https://data.humdata.org/dataset/cod-ab-phl',
}
''' % (json.dumps(rounded(mun['geometry'])), json.dumps(shapes, separators=(',', ':')))
(ROOT / 'app/data/boundaries.ts').write_text(ts)
print('barangays', len(shapes), 'bytes', len(ts))
