"""Builds the BetterCatarman logo files from Catarman's real boundary.

Boundary: OpenStreetMap relation 11760755 (© OpenStreetMap contributors, ODbL),
with the offshore municipal-waters section removed so only the land shape remains.
Run:  python3 scripts/build-logo.py
"""
import base64, math, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
BLUE, GOLD, INK = "#1d4ed8", "#ebcb4b", "#0b1f44"

LAND = [(124.4895003,12.3179044),(124.5426955,12.2857043),(124.5656973,12.3182243),(124.5738941,12.3365459),(124.585846,12.3347431),(124.5961886,12.3525186),(124.6078187,12.3509256),(124.6127325,12.3559771),(124.6471506,12.349605),(124.6541029,12.3502129),(124.6701318,12.3531684),(124.6780496,12.3599387),(124.6805602,12.3705234),(124.6883064,12.3724517),(124.6874154,12.3799468),(124.6887009,12.3825908),(124.6914474,12.3867615),(124.6916406,12.393489),(124.6965329,12.393971),(124.699022,12.3903243),(124.7061245,12.3929441),(124.7071759,12.399881),(124.7114675,12.4008869),(124.7141068,12.3980996),(124.7224323,12.4017461),(124.7255437,12.411491),(124.7321527,12.4111347),(124.7354786,12.4137123),(124.7058885,12.4887659),(124.7034208,12.491657),(124.6990435,12.5013146),(124.6842591,12.5065937),(124.6809906,12.5100548),
        # coastline (Philippine Sea) between the two shore points
        (124.6520,12.5185),(124.6230,12.5215),
        (124.5953914,12.5196251),(124.5902686,12.5085939),(124.5874853,12.5072626),(124.5850382,12.5066973),(124.5819839,12.5013905),(124.580117,12.4988556),(124.5761969,12.4901269),(124.5584136,12.4506845),(124.5534235,12.4405187),(124.5474797,12.4277365),(124.5418149,12.4180552),(124.5308929,12.4089812)]

H = 120.0  # map height in logo units
lon0 = min(p[0] for p in LAND); lat1 = max(p[1] for p in LAND); lat0 = min(p[1] for p in LAND)
k = H / (lat1 - lat0); cosl = math.cos(math.radians((lat0 + lat1) / 2))
pts = [((lon - lon0) * cosl * k, (lat1 - lat) * k) for lon, lat in LAND]
map_d = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z"

def sun(cx, cy, r):
    """Philippine-flag sun: a disc with eight rays, each made of one broad
    arrow-tipped beam flanked by two thin beams (as in the BetterSolano logo)."""
    def beam(angle, half_in, half_out, r_in, r_out, r_tip):
        a = math.radians(angle); ux, uy = math.cos(a), math.sin(a); vx, vy = -uy, ux
        loc = [(r_in, -half_in), (r_out, -half_out), (r_tip, 0), (r_out, half_out), (r_in, half_in)]
        pts = [(cx + r * (d * ux + o * vx), cy + r * (d * uy + o * vy)) for d, o in loc]
        return '<path d="M' + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + 'Z"/>'
    out = [f'<circle cx="{cx}" cy="{cy}" r="{r}"/>']
    for i in range(8):
        c = i * 45 - 90
        out.append(beam(c, 0.19, 0.25, 0.9, 1.78, 2.05))          # broad centre beam
        for side in (-15, 15):                                    # thin side beams
            out.append(beam(c + side, 0.045, 0.075, 0.97, 1.55, 1.68))
    return "".join(out)

# Mark: sun rising behind the north-west edge of the map. Local box 0 0 150 150.
MARK = (f'<g fill="{GOLD}">{sun(46, 54, 21)}</g>'
        # white halo separates the sun from the map, as in the reference
        f'<path transform="translate(22 26)" d="{map_d}" fill="#fff" stroke="#fff" stroke-width="9" stroke-linejoin="miter"/>'
        f'<path transform="translate(22 26)" d="{map_d}" fill="{BLUE}" stroke="{BLUE}" stroke-width="3" stroke-linejoin="miter"/>')

font = base64.b64encode((ROOT / "node_modules/@fontsource-variable/public-sans/files/public-sans-latin-wght-normal.woff2").read_bytes()).decode()
style = ("<style>@font-face{font-family:'Public Sans Logo';font-weight:100 900;"
         f"src:url(data:font/woff2;base64,{font}) format('woff2')}}"
         "text{font-family:'Public Sans Logo','Public Sans','Helvetica Neue',Arial,sans-serif;font-weight:700}</style>")

def lockup(ink):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 372 160" role="img" aria-label="BetterCatarman.org">{style}'
            f'<g transform="translate(0 4)">{MARK}</g>'
            f'<g fill="{ink}"><text x="166" y="76" font-size="42" letter-spacing="-1">Better</text>'
            f'<text x="166" y="118" font-size="42" letter-spacing="-1">Catarman</text>'
            f'<text x="356" y="142" font-size="18" font-weight="600" text-anchor="end">.org</text></g></svg>')

(ROOT / "public/logo.svg").write_text(lockup(INK))
(ROOT / "public/logo-mark.svg").write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 150 150" role="img" aria-label="BetterCatarman">{MARK}</svg>')
(ROOT / "public/favicon.svg").write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="4 4 146 146">{MARK}</svg>')
(ROOT / "app/components/LogoMark.vue").write_text(
    '<!-- Generated by scripts/build-logo.py — do not edit by hand. -->\n<template>\n'
    f'  <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 150 150" aria-hidden="true">{MARK}</svg>\n</template>\n')
print("ok", len(map_d))
