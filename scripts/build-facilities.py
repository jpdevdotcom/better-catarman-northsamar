"""Generates app/data/facilities.ts: schools and public health facilities in Catarman.

Source: OpenStreetMap (data-sources/osm-schools-health-catarman.json), © OpenStreetMap contributors.
Each place is assigned to the official barangay it falls in (data-sources/, NAMRIA/PSA); places
outside Catarman's official boundary are dropped. Pharmacies, dental clinics and private doctors'
clinics are left out: this is a directory of schools and public-facing health facilities.
Run:  python3 -I scripts/build-facilities.py   (after scripts/build-boundaries.py)
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'scripts'))
from geo import contains  # noqa: E402

elements = json.loads((ROOT / 'data-sources/osm-schools-health-catarman.json').read_text())['elements']
bts = (ROOT / 'app/data/boundaries.ts').read_text()
shapes = json.loads(re.search(r'barangayShapes: Record<string, BarangayShape> = (\{.*\})\n', bts).group(1))
municipal = json.loads(re.search(r'municipalBoundary: Ring\[\]\[\] = (\[.*\])\n', bts).group(1))

# Left out on purpose: parts of a campus, duplicates, and names too vague to be useful.
SKIP = {
    'UEP - Japan Coco Coir', 'Department of Industrial Education building 2', 'UEP College of Veterinary Medicine',
    'Department of Fisheries and Aquatic resources', 'CA Department of Agronomy', 'Forestry Department',
    'Crop Production Department', 'UEP - Asian Development Foundation College', 'CA Department of Crop Sciences',
    'CAC Criminology Department', 'UEP College of Nursing', 'UEP dental and Medical Clinic',
    'EVCC',            # same campus as "Eastern Visayas Central Colleges Catarman Campus"
    'San Lorenzo',     # ambiguous name
    'Annex (GSTS)',    # annex of Global School for Technological Studies
    'Health Center',   # unnamed
}
# Clearer names for a few entries.
RENAME = {'Polangi National HIgh School': 'Polangi National High School',
          'Bangkerohan Elementary school': 'Bangkerohan Elementary School'}
HOSPITALS = {'Catarman Doctors Hospital'}   # tagged as a doctor's office in OSM


def school_level(t, name):
    isced = t.get('isced:level', '')
    lower = name.lower()
    if t.get('amenity') in ('college', 'university'):
        return 'College'
    if isced in ('0-2',) or 'integrated' in lower:
        return 'Integrated school'
    if isced in ('2', '2-3') or 'high school' in lower or 'academy' in lower:
        return 'High school'
    if t.get('amenity') == 'kindergarten' or 'preschool' in lower:
        return 'Preschool'
    if isced in ('0-1', '1') or any(k in lower for k in ('elementary', 'primary', 'central school', 'special education')):
        return 'Elementary school'
    return 'School'


out = []
for e in elements:
    t = e['tags']
    name = RENAME.get(t.get('name', ''), t.get('name', '')).strip()
    if not name or name in SKIP:
        continue
    amenity, healthcare = t.get('amenity', ''), t.get('healthcare', '')
    if name in HOSPITALS or amenity == 'hospital':
        kind, detail = 'health', 'Hospital'
    elif amenity == 'health_post' or 'health station' in name.lower() or 'health center' in name.lower():
        kind, detail = 'health', 'Health center or station'
    elif amenity in ('school', 'college', 'university', 'kindergarten'):
        kind, detail = 'school', school_level(t, name)
    else:
        continue  # pharmacies, dentists, private clinics, laboratories
    c = e.get('center', e)
    lat, lng = c['lat'], c['lon']
    if not contains({'type': 'MultiPolygon', 'coordinates': municipal}, lng, lat):
        continue
    brgy = next((s for s, sh in shapes.items() if contains({'type': 'MultiPolygon', 'coordinates': sh['polygons']}, lng, lat)), None)
    operator = t.get('operator', '')
    item = {
        'name': name, 'kind': kind, 'detail': detail, 'barangay': brgy,
        'lat': round(lat, 5), 'lng': round(lng, 5),
        'osm': f"https://www.openstreetmap.org/{e['type']}/{e['id']}",
    }
    m = re.match(r'(.+? District)\b', operator)
    if m and 'District of' in operator:
        item['district'] = f'{m.group(1)}, DepEd'
    out.append(item)

order = {'Hospital': 0, 'Health center or station': 1, 'College': 2, 'High school': 3, 'Integrated school': 4,
         'Elementary school': 5, 'Preschool': 6, 'School': 7}
out.sort(key=lambda f: (f['kind'] != 'health', order[f['detail']], f['name']))

ts = '''// Generated by scripts/build-facilities.py from data-sources/. Edit the script, not this file.
// Places: © OpenStreetMap contributors (ODbL). Barangay: from the official NAMRIA/PSA boundaries.

export interface Facility {
  name: string
  kind: 'school' | 'health'
  /** Type of school or health facility. */
  detail: string
  /** Barangay slug, from the official boundaries. */
  barangay: string | null
  lat: number
  lng: number
  /** The place on OpenStreetMap, where anyone can correct it. */
  osm: string
  /** DepEd school district, when OpenStreetMap records it. */
  district?: string
}

export const facilities: Facility[] = %s

export const facilitiesRetrieved = '14 November 2026'
''' % json.dumps(out, ensure_ascii=False, indent=2)
(ROOT / 'app/data/facilities.ts').write_text(ts)
from collections import Counter
print(len(out), Counter(f['detail'] for f in out), 'no barangay:', [f['name'] for f in out if not f['barangay']])
